import { chromium } from 'playwright-core';
const [url, out] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
await p.route(/open-meteo/, (r) => r.abort());
await p.goto(url);
await p.waitForFunction(() => window.__drive && window.__drive.tick, null, { timeout: 500000 });
await p.evaluate(() => { const d = window.__drive; d.manual = true; for (let i = 0; i < 400 && d.state !== 'driving'; i++) d.tick(1 / 60); });
await p.waitForTimeout(4000);
await p.screenshot({ path: out, timeout: 240000, clip: { x: 0, y: 0, width: 390, height: 200 } });
await b.close();
